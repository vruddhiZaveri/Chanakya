from sqlalchemy import (CheckConstraint, Column, ForeignKey, ForeignKeyConstraint,
                        Integer, JSON, MetaData, String, Table, UniqueConstraint)

metadata = MetaData()
sessions = Table("sessions", metadata,
    Column("id", String(36), primary_key=True),
    Column("revision", Integer, nullable=False),
    Column("created_at", String, nullable=False),
    Column("updated_at", String, nullable=False),
    CheckConstraint("revision >= 1"),
    ForeignKeyConstraint(["id", "revision"], ["brief_versions.session_id", "brief_versions.revision"], deferrable=True, initially="DEFERRED"),
)
briefs = Table("brief_versions", metadata,
    Column("session_id", String(36), ForeignKey("sessions.id"), primary_key=True),
    Column("revision", Integer, primary_key=True),
    Column("brief", JSON, nullable=False),
    Column("reason", String, nullable=False),
    Column("created_at", String, nullable=False),
    CheckConstraint("revision >= 1"),
)
hypotheses = Table("hypotheses", metadata,
    Column("id", String(36), primary_key=True),
    Column("session_id", String(36), ForeignKey("sessions.id"), nullable=False, index=True),
    Column("revision", Integer, nullable=False),
    Column("created_at", String, nullable=False),
    CheckConstraint("revision >= 1"),
    UniqueConstraint("id", "session_id"),
    ForeignKeyConstraint(["id", "revision"], ["hypothesis_versions.hypothesis_id", "hypothesis_versions.revision"], deferrable=True, initially="DEFERRED"),
)
versions = Table("hypothesis_versions", metadata,
    Column("id", String(36), primary_key=True),
    Column("hypothesis_id", String(36), nullable=False),
    Column("session_id", String(36), nullable=False),
    Column("revision", Integer, nullable=False),
    Column("previous_revision", Integer),
    Column("previous_version_id", String(36)),
    Column("brief_revision", Integer, nullable=False),
    Column("type", String, nullable=False),
    Column("status", String, nullable=False),
    Column("content", JSON, nullable=False),
    Column("reason", String, nullable=False),
    Column("created_at", String, nullable=False),
    UniqueConstraint("hypothesis_id", "revision"),
    UniqueConstraint("hypothesis_id", "revision", "id"),
    CheckConstraint("revision >= 1 AND brief_revision >= 1"),
    CheckConstraint("(revision = 1 AND previous_revision IS NULL AND previous_version_id IS NULL) OR (revision > 1 AND previous_revision = revision - 1 AND previous_version_id IS NOT NULL)"),
    CheckConstraint("type IN ('factual','causal','comparative','predictive','diagnostic','normative')"),
    CheckConstraint("status IN ('proposed','under_investigation','supported','challenged','revised','resolved','inconclusive')"),
    ForeignKeyConstraint(["hypothesis_id", "session_id"], ["hypotheses.id", "hypotheses.session_id"]),
    ForeignKeyConstraint(["session_id", "brief_revision"], ["brief_versions.session_id", "brief_versions.revision"]),
    ForeignKeyConstraint(["hypothesis_id", "previous_revision", "previous_version_id"], ["hypothesis_versions.hypothesis_id", "hypothesis_versions.revision", "hypothesis_versions.id"]),
)
